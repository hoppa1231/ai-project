#!/usr/bin/env python3
"""Generate an auditable, pinned SQL migration from the compact GitHub community list."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import urllib.request

ROOT = Path(__file__).resolve().parents[2]
REVISION = 'e4a533393591266062b60beed3406dca4962e024'
REPO = 'https://raw.githubusercontent.com/runetfreedom/russia-blocked-geosite/'
# Preserve Russian services and shared DNS on the direct route.
DIRECT = {'habr.com', 'yandex.com', 'yandex.net', 'ya.ru', 'vk.com', 'vk.me', 'userapi.com',
          'mail.ru', 'my.com', 'ok.ru', 'ozon.com', 'avito.com', 'gosuslugi.ru',
          'cloudflare-dns.com', 'dns.google', 'googletagmanager.com'}
DOMAIN = re.compile(r'^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+$')

def normalize(raw):
    kept, excluded = set(), set()
    for line in raw.decode('utf-8').splitlines():
        value = line.strip().lower().rstrip('.')
        if not value or value.startswith('#'):
            continue
        try:
            value = value.encode('idna').decode('ascii')
        except UnicodeError:
            excluded.add(line)
            continue
        if (len(value) > 253 or not DOMAIN.fullmatch(value)
                or value.split('.')[-1] in {'ru', 'su', 'xn--p1ai'}
                or any(value == d or value.endswith('.' + d) for d in DIRECT)):
            excluded.add(value)
            continue
        kept.add(value)
    # A suffix covers its children; compact the response without widening routing.
    return sorted(d for d in kept if not any('.'.join(d.split('.')[i:]) in kept for i in range(1, len(d.split('.'))))), sorted(excluded)

def render(domains, revision):
    array = ','.join("'" + d + "'" for d in domains)
    return f'''-- Generated by ops/routing-lists/import.py; upstream release {revision}.
-- Data: runetfreedom/russia-blocked-geosite, GPL-3.0; see resources/routing/README.md.
UPDATE routing_default_rules SET editable = FALSE, enabled = TRUE WHERE action = 'VPN';
DELETE FROM user_route_rules WHERE default_rule_key IS NOT NULL;
INSERT INTO routing_default_rules
(rule_key, name, description, priority, enabled, match_type, match_values, action, editable, revision)
VALUES ('vpn-blocked-community', 'Заблокированные ресурсы',
 'GitHub runetfreedom / antifilter community; с исключением российских доменов',
 510, TRUE, 'DOMAIN_SUFFIX', ARRAY[{array}]::text[], 'VPN', FALSE, 1)
ON CONFLICT (rule_key) DO UPDATE SET match_values = EXCLUDED.match_values,
 description = EXCLUDED.description, enabled = TRUE, editable = FALSE,
 revision = routing_default_rules.revision + 1;
UPDATE policies SET version = version + 1;
'''

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--revision', default=REVISION)
    parser.add_argument('--source', type=Path, help='Use saved upstream file without network')
    parser.add_argument('--output', type=Path, default=ROOT / 'backend/src/main/resources/db/migration/V15__mandatory_services_community_domains.sql')
    args = parser.parse_args()
    if not re.fullmatch('[0-9a-f]{40}', args.revision):
        parser.error('revision must be an immutable full Git commit SHA')
    url = REPO + args.revision + '/antifilter-download-community.txt'
    raw = args.source.read_bytes() if args.source else urllib.request.urlopen(url, timeout=30).read()
    domains, excluded = normalize(raw)
    if not 100 <= len(domains) <= 2000:
        raise ValueError('Unexpected source size; manual review required')
    data = ROOT / 'backend/src/main/resources/routing'
    data.mkdir(parents=True, exist_ok=True)
    (data / 'upstream-community.txt').write_bytes(raw)
    (data / 'blocked-community.txt').write_text('\n'.join(domains) + '\n')
    metadata = dict(source=url, revision=args.revision, sha256=hashlib.sha256(raw).hexdigest(),
                    raw_bytes=len(raw), domains=len(domains), excluded=excluded, license='GPL-3.0')
    (data / 'source.json').write_text(json.dumps(metadata, ensure_ascii=False, indent=2) + '\n')
    args.output.write_text(render(domains, args.revision))
    print(json.dumps({k: v for k, v in metadata.items() if k != 'excluded'}))

if __name__ == '__main__':
    main()
